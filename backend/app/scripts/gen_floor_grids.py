def pad_row(row: str, width: int = GRID_COLS) -> str:
    """Pad with '.' or truncate to exactly `width` characters."""
    if len(row) > width:
        return row[:width]
    if len(row) < width:
        return row + "." * (width - len(row))
    return row


def main() -> None:
    with open(SCHEMA_PATH) as f:
        data = json.load(f)

    for floor in data["floors"]:
        fn = floor["floor_number"]
        if fn not in FLOOR_GRIDS:
            print(f"WARNING: no grid template for floor {fn}, skipping")
            continue
        grid = [pad_row(r) for r in FLOOR_GRIDS[fn]]
        # Verify uniform width
        widths = {len(r) for r in grid}
        assert widths == {GRID_COLS}, f"Floor {fn} has non-uniform widths: {widths}"
        floor["grid"] = grid
        print(
            f"Floor {fn:2d}: {len(grid)} rows x {GRID_COLS} cols | "
            f'D={sum(r.count("D") for r in grid)} '
            f'F={sum(r.count("F") for r in grid)} '
            f'E={sum(r.count("E") for r in grid)} '
            f'P={sum(r.count("P") for r in grid)}'
        )

    with open(SCHEMA_PATH, "w") as f:
        json.dump(data, f, indent=2)
    print("Wrote", SCHEMA_PATH)


if __name__ == "__main__":
    main()
